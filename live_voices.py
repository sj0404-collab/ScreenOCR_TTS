def _detect_emotion(text):
    """Detect emotion from text using word dictionaries."""
    t = text.lower().strip()
    # Remove punctuation for matching
    t_clean = re.sub(r'[!?.,;:\-…]+', ' ', t).strip()

    # Check each dictionary (order matters — first match wins)
    # Priority: shout > anger > pain > fear > surprise > laugh > joy > love > sad > annoy > sarcasm > think

    # SHOUT — uppercase or repeated chars
    if re.search(r'[А-ЯЁ]{2,}', text):
        return 'shout'
    if re.search(r'([а-яё])\1{3,}', text, re.IGNORECASE):
        return 'shout'

    # Check word dictionaries
    for word in D_ANGER:
        if word in t_clean:
            return 'anger'
    for word in D_PAIN:
        if word in t_clean:
            return 'pain'
    for word in D_FEAR:
        if word in t_clean:
            return 'fear'
    for word in D_SURPRISE:
        if word in t_clean:
            return 'surprise'
    for word in D_LAUGH:
        if word in t_clean:
            return 'laugh'
    for word in D_JOY:
        if word in t_clean:
            return 'joy'
    for word in D_LOVE:
        if word in t_clean:
            return 'love'
    for word in D_SAD:
        if word in t_clean:
            return 'sad'
    for word in D_ANNOY:
        if word in t_clean:
            return 'annoy'
    for word in D_SARCASM:
        if word in t_clean:
            return 'sarcasm'
    for word in D_WHISPER:
        if word in t_clean:
            return 'whisper'
    for word in D_THINK:
        if word in t_clean:
            return 'think'

    # Fallback: ? = surprise
    if '?' in text:
        return 'surprise'

    return 'normal'


