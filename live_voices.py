ARCH_MOD = {
    'genki': 1.4, 'kuudere': 0.4, 'yandere': 1.6,
    'imouto': 1.2, 'onee-san': 0.8, 'senpai': 0.7,
    'shounen': 1.3, 'sensei': 0.6,
}


def _fmt_rate(val):
    if val >= 0:
        return "+%d%%" % val
    return "%d%%" % val


def _fmt_pitch(val):
    if val >= 0:
        return "+%dHz" % val
    return "%dHz" % val


def _get_segments(text, archetype):
    """Return list of (text, rate, pitch) tuples."""
    mod = ARCH_MOD.get(archetype, 1.0)
    emotion = _detect_emotion(text)
    defaults = EMOTION_DEFAULTS.get(emotion, EMOTION_DEFAULTS['normal'])

    # SHOUT — dynamic crescendo (multiple segments)
    if emotion == 'shout':
        m = re.search(r'([а-яёА-ЯЁ])\1*', text)
        char_len = len(m.group(0)) if m else 3
        n_segs = min(max(3, char_len), 6)
        result = []
        for i in range(n_segs):
            frac = (i + 1) / n_segs
            r = int((20 + defaults['rate'] * frac) * mod)
            p = int((8 + defaults['pitch'] * frac) * mod)
            result.append((text, _fmt_rate(r), _fmt_pitch(p)))
        return result

    # All other emotions — single segment
    r = int(defaults['rate'] * mod)
    p = int(defaults['pitch'] * mod)
    return [(text, _fmt_rate(r), _fmt_pitch(p))]


async def _generate_anime(voice, text, archetype):
    text = _preprocess(text)
    sentences = _split_sentences(text)
    if not sentences:
        return b''

    all_parts = []
    for sent in sentences:
        segs = _get_segments(sent, archetype)
        for seg_text, rate, pitch in segs:
            try:
                mp3 = await _generate_edge(voice, seg_text, rate=rate, pitch=pitch)
                if mp3:
                    all_parts.append(mp3)
            except Exception:
                pass

    return b''.join(all_parts) if all_parts else b''


