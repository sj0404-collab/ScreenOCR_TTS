import asyncio
import io
import re

import edge_tts


async def _generate_edge(voice, text, rate="+0%", pitch="+0Hz"):
    comm = edge_tts.Communicate(text=text, voice=voice, rate=rate, pitch=pitch)
    buf = io.BytesIO()
    async for chunk in comm.stream():
        if chunk["type"] == "audio":
            buf.write(chunk["data"])
    return buf.getvalue()


